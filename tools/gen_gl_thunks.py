#!/usr/bin/env python3
"""Generate src/gl/gl_thunks.inc: a SysV-ABI thunk for every OpenGL command in the Khronos registry.

The game calls GL with the System V calling convention; opengl32 / the driver use the Microsoft one. Only the
register class of each argument matters for the conversion, so every parameter is classified as F (float),
D (double) or I (anything else: integers, enums, pointers, handles; passed as 64-bit) and each thunk is

    static SYSV RET t_glFoo(A a0, B a1, ...) { return ((RET (__stdcall*)(A, B, ...))p[N])(a0, a1, ...); }

with p[N] the real entry point, filled after a context is made current (src/gl/gl_bridge.cpp).

  python tools/gen_gl_thunks.py [--xml tools/data/gl.xml] [--out src/gl/gl_thunks.inc]
"""
import argparse, os, xml.etree.ElementTree as ET

ROOT = os.path.join(os.path.dirname(__file__), "..")
FLOAT = {"GLfloat", "GLclampf"}
DOUBLE = {"GLdouble", "GLclampd"}


def classify(ptype, text):
    if "*" in text:
        return "I"
    if ptype in FLOAT:
        return "F"
    if ptype in DOUBLE:
        return "D"
    return "I"


CTYPE = {"I": "uint64_t", "F": "float", "D": "double", "V": "void"}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--xml", default=os.path.join(ROOT, "tools", "data", "gl.xml"))
    ap.add_argument("--out", default=os.path.join(ROOT, "src", "gl", "gl_thunks.inc"))
    a = ap.parse_args()
    reg = ET.parse(a.xml).getroot()
    cmds = []
    for c in reg.find("commands").findall("command"):
        proto = c.find("proto")
        name = proto.find("name").text
        ptype = proto.find("ptype")
        ptext = "".join(proto.itertext())
        if ptext.strip().startswith("void") and "*" not in ptext:
            ret = "V"
        else:
            ret = classify(ptype.text if ptype is not None else "", ptext.replace(name, ""))
        params = []
        for p in c.findall("param"):
            pt = p.find("ptype")
            txt = "".join(p.itertext())
            params.append(classify(pt.text if pt is not None else "", txt.rsplit(p.find("name").text, 1)[0]))
        cmds.append((name, ret, params))
    cmds.sort()
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w") as f:
        f.write("// Generated by tools/gen_gl_thunks.py from the Khronos gl.xml. Do not edit.\n")
        f.write(f"#define GL_THUNK_COUNT {len(cmds)}\n")
        f.write("static void* g_gl_real[GL_THUNK_COUNT];\n")
        for i, (name, ret, params) in enumerate(cmds):
            decl = ", ".join(f"{CTYPE[t]} a{k}" for k, t in enumerate(params)) or "void"
            types = ", ".join(CTYPE[t] for t in params) or "void"
            args = ", ".join(f"a{k}" for k in range(len(params)))
            r = "" if ret == "V" else "return "
            f.write(f"static SYSV {CTYPE[ret]} t_{name}({decl}) {{ {r}reinterpret_cast<{CTYPE[ret]} (__stdcall*)({types})>(g_gl_real[{i}])({args}); }}\n")
        f.write("struct GlThunk { const char* name; void* thunk; };\n")
        f.write("static const GlThunk g_gl_thunks[GL_THUNK_COUNT] = {\n")
        for name, _, _ in cmds:
            f.write(f'    {{"{name}", reinterpret_cast<void*>(&t_{name})}},\n')
        f.write("};\n")
    print(len(cmds), "commands ->", a.out)


if __name__ == "__main__":
    main()
